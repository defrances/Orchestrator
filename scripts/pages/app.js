  function uniqueKbMap(list) {
    var map = {};
    (list || []).forEach(function (item, index) {
      var kb = String(item.kb || "").trim() || ("row-" + index);
      if (!map[kb]) {
        map[kb] = item;
        return;
      }
      if (item.include_in_deploy && !map[kb].include_in_deploy) map[kb] = item;
    });
    return map;
  }

  function uniquePackages(run) {
    var map = uniqueKbMap(packages(run));
    return Object.keys(map).map(function (kb) { return map[kb]; });
  }

  function uniqueCounts(run) {
    var rec = 0;
    var hold = 0;
    uniquePackages(run).forEach(function (item) {
      if (item.include_in_deploy) rec += 1;
      else hold += 1;
    });
    return { applicable: rec + hold, recommended: rec, held: hold };
  }

  function stationCount(bundle) {
    var counts = (bundle && bundle.counts) || {};
    if (counts.stations) return Number(counts.stations) || 0;
    var seen = {};
    ((bundle && bundle.packages) || []).forEach(function (item) {
      (item.stations || []).forEach(function (name) {
        if (name) seen[name] = 1;
      });
    });
    return Object.keys(seen).length;
  }

