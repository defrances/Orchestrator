  function trendChart() {
    var points = allSnapshots().map(function (item) {
      var counts = uniqueCounts(item);
      return {
        run_id: item.run_id,
        created_at: item.created_at,
        recommended: counts.recommended,
        held: counts.held
      };
    });
    if (!points.length) return '<p class="empty">History will grow with later runs.</p>';
    var w = 700;
    var h = 180;
    var padL = 28;
    var padR = 12;
    var padT = 16;
    var padB = 24;
    var innerW = w - padL - padR;
    var innerH = h - padT - padB;
    var max = 1;
    points.forEach(function (p) {
      if (p.recommended > max) max = p.recommended;
      if (p.held > max) max = p.held;
    });
    function xAt(i) {
      if (points.length === 1) return padL + innerW / 2;
      return padL + i * innerW / (points.length - 1);
    }
    function yAt(v) { return padT + innerH - (Number(v) / max) * innerH; }
    function path(key) {
      return points.map(function (p, i) {
        return (i ? "L" : "M") + xAt(i) + " " + yAt(p[key]);
      }).join(" ");
    }
    var first = String(points[0].created_at || "").slice(0, 10);
    var last = String(points[points.length - 1].created_at || "").slice(0, 10);
    return '<div class="trend"><svg viewBox="0 0 ' + w + " " + h +
      '" preserveAspectRatio="none"><path d="' + path("held") +
      '" fill="none" stroke="#0b57b8" stroke-width="4"/><path d="' + path("recommended") +
      '" fill="none" stroke="#ef3e4e" stroke-width="3"/></svg><div class="axis"><span>' +
      esc(first) + "</span><span>" + esc(last) + "</span></div></div>";
  }

